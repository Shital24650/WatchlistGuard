_pools = {}
_pool_lock = Lock()


class HybridRow(dict):
    """Mapping row that preserves existing SQLite integer indexing."""
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class PostgresConnection:
    """Connection adapter for qmark SQL and pooled PostgreSQL leases."""
    def __init__(self, raw, pool):
        self.raw = raw
        self.pool = pool

    @staticmethod
    def _sql(sql):
        # psycopg treats percent signs as placeholder syntax when parameters
        # are supplied. Escape SQL literals before translating qmark binds.
        return sql.replace("%", "%%").replace("?", "%s")

    def execute(self, sql, params=()):
        return self.raw.execute(self._sql(sql), params)

    def executemany(self, sql, params):
        with self.raw.cursor() as cursor:
            cursor.executemany(self._sql(sql), params)
            return cursor.rowcount

    def __enter__(self):
        # Pooled PostgreSQL connections use autocommit=True. A top-level
        # context therefore opens a real transaction even when reads occurred
        # before entry; only explicit nesting inside a context creates a savepoint.
        self._transaction = self.raw.transaction()
        self._transaction.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        return self._transaction.__exit__(exc_type, exc, tb)

    def commit(self):
        return self.raw.commit()

    def rollback(self):
        return self.raw.rollback()

    def close(self):
        close(self)


def database_url(path=None):
    return path or os.environ.get("WATCHLISTGUARD_DATABASE_URL") or os.environ.get(
        "WATCHLISTGUARD_DB", "data/watchlistguard.db")


def dialect(conn):
    return "postgresql" if isinstance(conn, PostgresConnection) else "sqlite"


def is_postgres_url(path):
    return isinstance(path, str) and path.startswith(("postgres://", "postgresql://"))


def connect(path=None):
    """Return a SQLite connection or a pooled psycopg 3 PostgreSQL lease."""
    path = database_url(path)
    if is_postgres_url(path):
        try:
            from psycopg_pool import ConnectionPool
        except ImportError as exc:
            raise RuntimeError("PostgreSQL requires psycopg[binary,pool] 3") from exc
        with _pool_lock:
            pool = _pools.get(path)
            if pool is None or pool.closed:
                pool = ConnectionPool(path, min_size=1, max_size=int(os.getenv("WATCHLISTGUARD_DB_POOL_SIZE", "5")),
                                      kwargs={"autocommit": True}, open=True, timeout=5)
                _pools[path] = pool
        raw = pool.getconn(timeout=5)
        raw.row_factory = lambda cursor: lambda values: HybridRow(zip((c.name for c in cursor.description), values))
        return PostgresConnection(raw, pool)
    if path != ":memory:":
        Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path, timeout=5)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def close(conn):
    """Return a pooled PostgreSQL lease or close a normal SQLite connection."""
    if dialect(conn) == "postgresql":
        try:
            from psycopg.pq import TransactionStatus
            if conn.raw.info.transaction_status != TransactionStatus.IDLE:
                conn.raw.rollback()
        except Exception:
            # Ensure a failed lease cannot be handed to the next borrower.
            conn.raw.close()
        finally:
            conn.pool.putconn(conn.raw)
    else:
        conn.close()


def close_pools():
    """Close every pool after request/worker activity has stopped."""
    with _pool_lock:
        pools = tuple(_pools.values())
        _pools.clear()
        for pool in pools:
            pool.close()


def begin_write(conn):
    """Acquire the write serialization point used by idempotent ingestion."""
    if dialect(conn) == "sqlite":
        conn.execute("BEGIN IMMEDIATE")
    # PostgreSQL obtains its serialization lock through a transaction-scoped
    # advisory lock, so fingerprint checks and insertion are atomic across workers.
    else:
        conn.execute("SELECT pg_advisory_xact_lock(731942816)")


def begin_admin_write(conn):
    """Serialize administrator invariant changes across concurrent writers."""
    if dialect(conn) == "sqlite":
        conn.execute("BEGIN IMMEDIATE")
    else:
        conn.execute("SELECT pg_advisory_xact_lock(731942819)")


def execute_script(conn, script):
    if dialect(conn) == "sqlite":
        conn.executescript(script)
    else:
        for statement in script.split(";"):
            if statement.strip():
                conn.execute(statement)


def initialize(conn):
    """Initialize SQLite demo schema; require explicit Alembic for PostgreSQL."""
    if dialect(conn) == "postgresql":
        try:
            version = conn.execute("SELECT version_num FROM alembic_version").fetchone()
            conn.commit()
            if version is None:
                raise RuntimeError("PostgreSQL has no applied migration; run `alembic upgrade head` explicitly")
        except Exception as exc:
            conn.rollback()
            raise RuntimeError("PostgreSQL schema is not migrated; run `alembic upgrade head` explicitly") from exc
    else:
        conn.executescript(SQLITE_SCHEMA)
        conn.commit()


