"""Dialect-aware database connections and schema initialization.

SQLite remains the default. PostgreSQL uses psycopg 3 and a bounded connection
pool; select it with WATCHLISTGUARD_DATABASE_URL (or a postgres URL in --db).
Alembic is the production schema versioning mechanism; initialize() remains for
the backwards-compatible SQLite demo and isolated test databases.
"""
